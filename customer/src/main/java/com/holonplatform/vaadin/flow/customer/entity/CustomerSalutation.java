package com.holonplatform.vaadin.flow.customer.entity;

/**
 * Formal salutation / honorific prefix for individual contacts.
 * Maps to the i18n key prefix {@code customer.salutation.*}.
 */
public enum CustomerSalutation {

    /** No salutation — name used directly. */
    NONE,

    /** Mr. */
    MR,

    /** Mrs. */
    MRS,

    /** Ms. */
    MS,

    /** Dr. */
    DR,

    /** Prof. */
    PROF
}

